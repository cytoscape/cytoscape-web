// Browser benchmark: the real app, booted headless in Chromium, timed from
// inside the page. The minimal first cut of the v4 harness's render bench.
//
//   npm run build                    # the bench drives the built dist/
//   npm run benchmark:browser        # standalone: results file + report
//   npm run benchmark -- --renderer  # as a job in a report run
//   node --import tsx benchmark/browser-bench.mjs --json out.json
//
// Two scenario groups, one suite ('browser — app'):
//
//   boot — the app's own `cyweb.boot.*` User Timing marks (bootMarks.ts),
//     read as time-from-navigation-start per milestone. One page load, so
//     these are one-shot rows (samples: 1) — the comparison lists them
//     unscreened rather than ranking them, which is honest for boot times.
//   load — `CyWebApi.network.createNetworkFromCx2` with a BENCH_N-sized
//     document generated by the shared fixture, sampled LOAD_SAMPLES times
//     in-page with `performance.now`. This is the real end-to-end import a
//     user feels: validate + convert + store updates + the renderer's
//     reaction, in the browser's JIT and memory, not Node's.
//
// What would make these numbers move: anything on the boot path (bundle
// size, hydration, auth settling) moves the boot rows; the load row tracks
// the whole import pipeline including store writes the Node suites cannot
// see. The dist/ bundle is the subject: a stale build measures old code,
// hence the mtime warning.
//
// The server is a hand-rolled node:http static server on an ephemeral port
// (the e2e stack owns port 5500 and its rules; this bench never touches it).
// Keycloak's silent SSO cannot reach its server from here — the app's boot
// is expected to settle anonymously; if it stops doing so, the whenReady
// wait below times out and the run fails loudly rather than measuring a
// wedged page.

import { createServer } from 'node:http'
import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs'
import { readdirSync } from 'node:fs'
import { dirname, join, extname, normalize } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from '@playwright/test'
import { toStats, oneShotStats } from './render-stats.mjs'
import { buildMeta } from './run-meta.mjs'
import { stampHarness } from './harness-id.mjs'
import { renderReport } from './report-html.mjs'
import { makeCx2, N, E } from './fixture.mjs'

const DIR = dirname(fileURLToPath(import.meta.url))
const ROOT = join(DIR, '..')
const DIST = join(ROOT, 'dist')
const RESULTS_DIR = join(DIR, 'results')

const LOAD_SAMPLES = 5
const READY_TIMEOUT_MS = 60000

const argv = process.argv.slice(2)
const jsonAt = argv.indexOf('--json')
const jsonPath = jsonAt >= 0 ? argv[jsonAt + 1] : null
const headed = argv.includes('--headed')

// -- preflight ---------------------------------------------------------------

if (!existsSync(join(DIST, 'index.html'))) {
  console.error(
    'browser-bench: no dist/index.html — run `npm run build` first.',
  )
  process.exit(1)
}

// warn when the bundle predates the newest source file: a stale build
// measures old code and the report would attribute it to HEAD
function newestMtime(dir, ext) {
  let newest = 0

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)

    if (entry.isDirectory()) {
      newest = Math.max(newest, newestMtime(path, ext))
    } else if (ext.test(entry.name)) {
      newest = Math.max(newest, statSync(path).mtimeMs)
    }
  }

  return newest
}

const distMtime = statSync(join(DIST, 'index.html')).mtimeMs

if (newestMtime(join(ROOT, 'src'), /\.(m?[jt]sx?|json|css)$/) > distMtime) {
  console.warn(
    'browser-bench: WARNING — src/ is newer than dist/; the bench will',
    'measure a stale build. Re-run `npm run build`.',
  )
}

// -- static server (ephemeral port; SPA fallback to index.html) --------------

const MIME = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.mjs': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.wasm': 'application/wasm',
  '.map': 'application/json',
}

const server = createServer((req, res) => {
  const urlPath = decodeURIComponent(new URL(req.url, 'http://x').pathname)
  const safe = normalize(urlPath).replace(/^(\.\.[/\\])+/, '')
  let file = join(DIST, safe)

  if (!file.startsWith(DIST) || !existsSync(file) || safe === '/') {
    file = join(DIST, 'index.html') // SPA fallback
  }

  try {
    const body = readFileSync(file)

    res.writeHead(200, {
      'content-type': MIME[extname(file)] ?? 'application/octet-stream',
    })
    res.end(body)
  } catch {
    res.writeHead(404)
    res.end()
  }
})

await new Promise((ok) => server.listen(0, '127.0.0.1', ok))

const base = `http://127.0.0.1:${server.address().port}`

console.log(`browser-bench: serving dist/ at ${base}`)

// -- drive the page ----------------------------------------------------------

const failures = []
const groups = []
const startedAt = Date.now()
const browser = await chromium.launch({ headless: !headed })
const context = await browser.newContext({
  viewport: { width: 1280, height: 800 },
})
const page = await context.newPage()

try {
  await page.goto(base)
  await page.waitForFunction(() => globalThis.CyWebApi != null, null, {
    timeout: READY_TIMEOUT_MS,
  })
  await page.evaluate(
    (timeout) =>
      Promise.race([
        globalThis.CyWebApi.whenReady(),
        new Promise((_, no) =>
          setTimeout(() => no(new Error('whenReady timed out')), timeout),
        ),
      ]),
    READY_TIMEOUT_MS,
  )

  // boot: every cyweb.boot.* mark, as time from navigation start (one-shot)
  const bootMarks = await page.evaluate(() =>
    performance
      .getEntriesByType('mark')
      .filter((m) => m.name.startsWith('cyweb.boot.'))
      .map((m) => ({
        name: m.name.slice('cyweb.boot.'.length),
        ms: m.startTime,
      })),
  )

  groups.push({
    name: 'browser: boot (ms from navigation start)',
    benches: bootMarks.map((m) => ({
      name: m.name,
      stats: oneShotStats(m.ms),
    })),
  })
  console.log(
    `  boot: ${bootMarks.map((m) => `${m.name} ${m.ms.toFixed(0)}ms`).join(' · ')}`,
  )

  // load: import a BENCH_N-sized CX2 through the public API, sampled
  const cx2 = makeCx2()
  const loadMs = []

  for (let s = 0; s < LOAD_SAMPLES; s++) {
    const ms = await page.evaluate((doc) => {
      const t0 = performance.now()
      const result = globalThis.CyWebApi.network.createNetworkFromCx2({
        cxData: doc,
        navigate: true,
        addToWorkspace: true,
      })

      if (result?.success === false) {
        throw new Error(`createNetworkFromCx2 failed: ${result.error?.message}`)
      }

      return performance.now() - t0
    }, cx2)

    loadMs.push(ms)
    console.log(`  load ${s + 1}/${LOAD_SAMPLES}: ${ms.toFixed(0)}ms`)
  }

  groups.push({
    name: `browser: load CX2 via CyWebApi (${N}n/${E}e)`,
    benches: [{ name: 'network.createNetworkFromCx2', stats: toStats(loadMs) }],
  })
} catch (e) {
  console.error(`browser-bench: FAILED — ${e.message}`)
  failures.push({ job: 'browser — app', error: String(e.message) })
} finally {
  await browser.close()
  server.close()
}

// -- emit --------------------------------------------------------------------

const version = browser.version?.() ?? null
const jobs =
  groups.length > 0
    ? [
        {
          suite: 'browser — app',
          n: N,
          op: null,
          context: { arch: null, runtime: 'chromium', cpu: null },
          groups,
          durationMs: Date.now() - startedAt,
        },
      ]
    : []

stampHarness(jobs, 'browser-bench.mjs')

if (jsonPath != null) {
  // the bundle report.mjs --renderer consumes
  writeFileSync(jsonPath, JSON.stringify({ jobs, failures, adapter: null }))
} else {
  const results = {
    meta: buildMeta({
      startedAt,
      profile: 'browser',
      failures,
      context: { arch: null, runtime: 'chromium', cpu: null },
    }),
    jobs,
  }

  results.meta.machine = {
    ...results.meta.machine,
    browser: { name: 'chromium', version },
  }

  const stamp = results.meta.date.replace(/[:.]/g, '-')
  const resultsPath = join(RESULTS_DIR, `results-browser-${stamp}.json`)

  writeFileSync(resultsPath, JSON.stringify(results, null, 2))
  writeFileSync(join(RESULTS_DIR, 'report.html'), renderReport(results))
  console.log(`\nreport:  ${join(RESULTS_DIR, 'report.html')}`)
  console.log(`results: ${resultsPath}`)
}

process.exit(failures.length > 0 ? 1 : 0)
